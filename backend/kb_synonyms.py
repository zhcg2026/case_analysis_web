def expand_query(query: str) -> list:
    """
    扩展查询词：从用户问题中提取关键词，用同义词映射扩展
    返回扩展后的查询词列表（去重）
    """
    import re
    expanded = set()

    # 提取中文片段
    chinese_blocks = re.findall(r'[一-龥]+', query)

    for block in chinese_blocks:
        # 完整块加入
        if 2 <= len(block) <= 12:
            expanded.add(block)

        # 2-4字子片段
        for length in [4, 3, 2]:
            for i in range(len(block) - length + 1):
                seg = block[i:i + length]
                if all('一' <= c <= '龥' for c in seg):
                    expanded.add(seg)

    # 同义词扩展
    synonym_expanded = set()
    for word in list(expanded):
        if word in SYNONYM_MAP:
            for syn in SYNONYM_MAP[word]:
                synonym_expanded.add(syn)
                # 同义词的子片段也加入
                for length in [4, 3, 2]:
                    for i in range(len(syn) - length + 1):
                        seg = syn[i:i + length]
                        if all('一' <= c <= '龥' for c in seg) and seg not in ['市容环', '容环卫', '环卫中']:
                            synonym_expanded.add(seg)

    expanded.update(synonym_expanded)
    return sorted(expanded, key=len, reverse=True)


def get_synonym_targets(keyword: str) -> list:
    """获取关键词的同义词映射目标"""
    return SYNONYM_MAP.get(keyword, [keyword])


def has_specific_facility(query: str) -> bool:
    """判断问题是否包含具体设施词"""
    for word in SPECIFIC_FACILITY_WORDS:
        if word in query:
            return True
    return False
